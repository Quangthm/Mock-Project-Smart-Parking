-- 1. BẢNG CẤU HÌNH ĐỊNH MỨC SỨC CHỨA VẬN HÀNH (OPERATIONAL CAPACITY CONFIGS)
-- Lưu trữ cấu hình hạn mức nhận đặt chỗ và sức chứa tối đa phục vụ tính toán khả dụng.
CREATE TABLE IF NOT EXISTS operational_capacity_configs (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    tenant_id UUID NOT NULL,
    site_id UUID NOT NULL,
    spatial_unit_id UUID NULL,
    vehicle_type VARCHAR(50) NOT NULL DEFAULT 'CAR' CHECK (vehicle_type IN ('CAR', 'MOTORCYCLE', 'OVERSIZED')),
    total_physical_capacity INT NOT NULL CHECK (total_physical_capacity >= 0),
    max_reservation_quota INT NOT NULL CHECK (max_reservation_quota >= 0 AND max_reservation_quota <= total_physical_capacity),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE NULLS NOT DISTINCT (site_id, spatial_unit_id, vehicle_type)
);
CREATE INDEX IF NOT EXISTS idx_op_capacity_site ON operational_capacity_configs(site_id, vehicle_type);

-- 2. BẢNG CHÍNH SÁCH VẬN HÀNH (OPERATIONAL POLICIES)
-- Quản lý các tham số cửa sổ thời gian (bounds) theo chuẩn SRS v1.0
CREATE TABLE IF NOT EXISTS operational_policies (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    tenant_id UUID NULL,
    site_id UUID NULL,
    version INT NOT NULL DEFAULT 1 CHECK (version > 0),
    effective_from TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    effective_until TIMESTAMPTZ NULL,
    arrival_late_tolerance_enabled BOOLEAN NULL,
    arrival_late_tolerance_minutes INT NULL CHECK (arrival_late_tolerance_minutes BETWEEN 15 AND 30),
    payment_hold_duration_minutes INT NULL CHECK (payment_hold_duration_minutes > 0),
    min_reservation_duration_minutes INT NULL CHECK (min_reservation_duration_minutes > 0),
    max_reservation_duration_hours INT NULL CHECK (max_reservation_duration_hours > 0),
    max_advance_booking_days INT NULL CHECK (max_advance_booking_days >= 0),
    inter_booking_buffer_minutes INT NULL CHECK (inter_booking_buffer_minutes >= 0),
    reservation_protection_window_hours INT NULL CHECK (reservation_protection_window_hours >= 0),
    allocation_lead_time_minutes INT NULL CHECK (allocation_lead_time_minutes >= 0),
    facility_failure_refund_lead_minutes INT NULL CHECK (facility_failure_refund_lead_minutes >= 0),
    occupancy_validity_timespan_hours INT NULL CHECK (occupancy_validity_timespan_hours >= 0),
    rapid_cancellation_count INT NULL CHECK (rapid_cancellation_count > 0),
    rapid_cancellation_window_minutes INT NULL CHECK (rapid_cancellation_window_minutes > 0),
    rapid_cancellation_restriction_minutes INT NULL CHECK (rapid_cancellation_restriction_minutes > 0),
    daily_cancellation_limit INT NULL CHECK (daily_cancellation_limit > 0),
    cancellation_timezone TEXT NULL CHECK (cancellation_timezone = 'Asia/Ho_Chi_Minh'),
    override_bounds JSONB NULL CHECK (jsonb_typeof(override_bounds) = 'object'),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ((tenant_id IS NULL AND site_id IS NULL) OR (tenant_id IS NOT NULL AND site_id IS NOT NULL)),
    CHECK (tenant_id IS DISTINCT FROM '00000000-0000-0000-0000-000000000000'::uuid AND
           site_id IS DISTINCT FROM '00000000-0000-0000-0000-000000000000'::uuid),
    CHECK (effective_until IS NULL OR effective_until > effective_from),
    CHECK (max_reservation_duration_hours * 60::bigint >= min_reservation_duration_minutes),
    CHECK (site_id IS NULL OR (override_bounds IS NULL AND rapid_cancellation_count IS NULL AND
        rapid_cancellation_window_minutes IS NULL AND rapid_cancellation_restriction_minutes IS NULL AND
        daily_cancellation_limit IS NULL AND cancellation_timezone IS NULL)),
    CHECK (site_id IS NOT NULL OR (arrival_late_tolerance_enabled IS NULL AND
        arrival_late_tolerance_minutes IS NOT NULL AND payment_hold_duration_minutes IS NOT NULL AND
        min_reservation_duration_minutes IS NOT NULL AND max_reservation_duration_hours IS NOT NULL AND
        max_advance_booking_days IS NOT NULL AND inter_booking_buffer_minutes IS NOT NULL AND
        reservation_protection_window_hours IS NOT NULL AND allocation_lead_time_minutes IS NOT NULL AND
        facility_failure_refund_lead_minutes IS NOT NULL AND occupancy_validity_timespan_hours IS NOT NULL AND
        rapid_cancellation_count IS NOT NULL AND rapid_cancellation_window_minutes IS NOT NULL AND
        rapid_cancellation_restriction_minutes IS NOT NULL AND daily_cancellation_limit IS NOT NULL AND
        cancellation_timezone IS NOT NULL)),
    CONSTRAINT operational_policy_effective_scope EXCLUDE USING gist (
        (COALESCE(tenant_id, '00000000-0000-0000-0000-000000000000'::uuid)) WITH =,
        (COALESCE(site_id, '00000000-0000-0000-0000-000000000000'::uuid)) WITH =,
        tstzrange(effective_from, effective_until, '[)') WITH &&
    ) WHERE (is_active)
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_operational_policy_revision
    ON operational_policies(COALESCE(tenant_id, '00000000-0000-0000-0000-000000000000'::uuid),
        COALESCE(site_id, '00000000-0000-0000-0000-000000000000'::uuid), version);
CREATE INDEX IF NOT EXISTS idx_operational_policies_site ON operational_policies(site_id);

-- 3. BẢNG POOL SỨC CHỨA THEO BÃI/KHU VỰC (SITE CAPACITY POOLS)
