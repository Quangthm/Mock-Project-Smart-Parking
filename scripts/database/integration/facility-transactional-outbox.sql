-- 1. Pre-flight check: canonical Facility schema must exist, and any preexisting
--    MassTransit outbox objects must not have incompatible schema shapes.
DO $preflight$
DECLARE
    tbl TEXT;
    expected_col RECORD;
    missing_base TEXT[] := ARRAY[]::TEXT[];
    conflicts TEXT[] := ARRAY[]::TEXT[];
BEGIN
    FOREACH tbl IN ARRAY ARRAY['tenants', 'parking_sites', 'parking_slots']
    LOOP
        IF to_regclass(format('public.%I', tbl)) IS NULL THEN
            missing_base := array_append(missing_base, tbl);
        END IF;
    END LOOP;

    IF cardinality(missing_base) > 0 THEN
        RAISE EXCEPTION USING
            MESSAGE = 'Facility base schema prerequisites are missing; aborting outbox migration.',
            DETAIL = format('Missing tables in public: %s', array_to_string(missing_base, ', '));
    END IF;

    FOR expected_col IN
        SELECT * FROM (VALUES
            ('InboxState', 'Id', 'bigint', true),
            ('InboxState', 'MessageId', 'uuid', true),
            ('InboxState', 'ConsumerId', 'uuid', true),
            ('InboxState', 'LockId', 'uuid', true),
            ('OutboxState', 'OutboxId', 'uuid', true),
            ('OutboxState', 'LockId', 'uuid', true),
