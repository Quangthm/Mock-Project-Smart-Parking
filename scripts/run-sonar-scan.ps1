<#
.SYNOPSIS
    Runs SonarQube scan with code coverage collection for SmartParking solution.
.DESCRIPTION
    1. Checks if SonarQube server is reachable at http://localhost:9000
    2. Ensures dotnet-sonarscanner is installed
    3. Runs SonarScanner begin with OpenCover report configuration
    4. Compiles solution and executes unit tests collecting coverage
    5. Finalizes scan and uploads results to SonarQube dashboard
.PARAMETER ProjectKey
    SonarQube project key (default: SmartParking)
.PARAMETER SonarUrl
    SonarQube server URL (default: http://localhost:9000)
.PARAMETER Token
    SonarQube authentication token or user credential (default: squ_e56510ca3bb5deb87199bd93f127520a40b8370a or admin:admin)
.PARAMETER Scope
    Target scope for coverage calculation:
    - 'All': Default Sonar analysis
    - 'Backend': Excludes FE, AI, and generated files from coverage
    - 'Core': Focuses on Domain & Application layers (industry standard for unit test coverage >= 80%)
.EXAMPLE
    .\scripts\run-sonar-scan.ps1
    .\scripts\run-sonar-scan.ps1 -Scope Core
#>
[CmdletBinding()]
param(
    [string]$ProjectKey = "SmartParking",
    [string]$SonarUrl = "http://localhost:9000",
    [string]$Token = "squ_e56510ca3bb5deb87199bd93f127520a40b8370a",
    [ValidateSet("All", "Backend", "Core")]
    [string]$Scope = "Backend"
)

$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path $PSScriptRoot -Parent
Set-Location $repoRoot

Write-Host "==========================================================" -ForegroundColor Cyan
Write-Host " [SmartParking] Running SonarQube Scan & Coverage Pipeline " -ForegroundColor Cyan
Write-Host " Scope: $Scope | ProjectKey: $ProjectKey" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Cyan

# 1. Verify SonarQube server is UP
Write-Host "`n[1/5] Checking SonarQube server at $SonarUrl..." -ForegroundColor Yellow
try {
    $statusResponse = Invoke-RestMethod -Uri "$SonarUrl/api/system/status" -TimeoutSec 5 -ErrorAction Stop
    if ($statusResponse.status -ne 'UP') {
        throw "SonarQube is not ready. Current status: $($statusResponse.status)"
    }
    Write-Host " -> SonarQube is UP (version: $($statusResponse.version))" -ForegroundColor Green
} catch {
    Write-Warning "Cannot connect to SonarQube at $SonarUrl."
    Write-Host "Ensure the SonarQube container is running via:" -ForegroundColor Yellow
    Write-Host "docker compose -p smartpark-sonar -f compose.sonar.yml up -d" -ForegroundColor Cyan
    exit 1
}

# 2. Check dotnet-sonarscanner
Write-Host "`n[2/5] Checking dotnet-sonarscanner tool..." -ForegroundColor Yellow
$scannerCheck = Get-Command dotnet-sonarscanner -ErrorAction SilentlyContinue
if (-not $scannerCheck) {
    Write-Host "Installing dotnet-sonarscanner globally..." -ForegroundColor Yellow
    dotnet tool install --global dotnet-sonarscanner
}
Write-Host " -> dotnet-sonarscanner is available." -ForegroundColor Green

# 3. Configure Coverage Exclusions based on Scope
$coverageExclusions = ""
switch ($Scope) {
    "Backend" {
        # Excludes Frontend, AI, tests, and autogenerated files from coverage calculation
        $coverageExclusions = "FE/**,ai/**,scripts/**,tests/**,**/*Migrations*/**,**/obj/**,**/*.g.cs"
    }
    "Core" {
        # Focuses coverage strictly on Domain, Application, and Core Business Services (Unit Test Scope)
        $coverageExclusions = "FE/**,ai/**,scripts/**,tests/**,**/*Migrations*/**,**/obj/**,**/*.g.cs,**/Program.cs,**/Persistence/**,**/API/**,**/*Controller*.cs"
    }
    Default {
        $coverageExclusions = "scripts/**,tests/**,**/*Migrations*/**,**/obj/**,**/*.g.cs"
    }
}

# 4. Clean previous test results
$testResultsDir = Join-Path $repoRoot "TestResults"
if (Test-Path $testResultsDir) {
    Remove-Item -Path $testResultsDir -Recurse -Force -ErrorAction SilentlyContinue
}

# 5. Execute Scan
Write-Host "`n[3/5] Starting SonarScanner begin step..." -ForegroundColor Yellow
$beginArgs = @(
    "begin",
    "/k:$ProjectKey",
    "/d:sonar.host.url=$SonarUrl",
    "/d:sonar.token=$Token",
    "/d:sonar.cs.opencover.reportsPaths=TestResults/**/coverage.opencover.xml"
)

if (![string]::IsNullOrEmpty($coverageExclusions)) {
    $beginArgs += "/d:sonar.coverage.exclusions=$coverageExclusions"
}

& dotnet-sonarscanner @beginArgs
if ($LASTEXITCODE -ne 0) {
    throw "SonarScanner begin failed with exit code $LASTEXITCODE."
}

Write-Host "`n[4/5] Building solution and running tests with coverage..." -ForegroundColor Yellow
dotnet build SmartParking.slnx
if ($LASTEXITCODE -ne 0) {
    throw "Build failed with exit code $LASTEXITCODE."
}

dotnet test SmartParking.slnx --no-build --collect:"XPlat Code Coverage;Format=opencover" --results-directory ./TestResults
if ($LASTEXITCODE -ne 0) {
    Write-Warning "Some tests did not pass. Check test logs."
}

Write-Host "`n[5/5] Finalizing SonarScanner and uploading reports..." -ForegroundColor Yellow
& dotnet-sonarscanner end /d:sonar.token=$Token
if ($LASTEXITCODE -ne 0) {
    throw "SonarScanner end failed with exit code $LASTEXITCODE."
}

Write-Host "`n==========================================================" -ForegroundColor Green
Write-Host " [SUCCESS] SonarQube analysis completed!" -ForegroundColor Green
Write-Host " View Dashboard: $SonarUrl/dashboard?id=$ProjectKey" -ForegroundColor Cyan
Write-Host "==========================================================" -ForegroundColor Green
