import { useState } from "react"

import { request } from "../../lib/authApi"

export function AccountSecurityPanel() {
  const [setup, setSetup] = useState<{ secret: string; uri: string } | null>(
    null,
  )
  const [code, setCode] = useState("")
  const [message, setMessage] = useState("")
  const [busy, setBusy] = useState(false)

  async function start() {
    setBusy(true)
    setMessage("")
    try {
      setSetup(
        (
          await request<{ data: { secret: string; uri: string } }>(
            "/mfa/setup",
            "POST",
          )
        ).data,
      )
    } catch (e) {
      setMessage(e instanceof Error ? e.message : "Setup failed.")
    } finally {
      setBusy(false)
    }
  }

  async function enable(e: React.FormEvent) {
    e.preventDefault()
    setBusy(true)
    try {
      await request("/mfa/enable", "POST", { code })
      setSetup(null)
      setCode("")
      setMessage(
        "Two-factor authentication enabled. You will need to enter your security code each time you sign in.",
      )
    } catch (e) {
      setMessage(e instanceof Error ? e.message : "Activation failed.")
    } finally {
      setBusy(false)
    }
  }

  return (
    <section className="card" style={{ display: "flex", flexDirection: "column", gap: "1rem" }}>
      <div>
        <h3 style={{ margin: "0 0 0.25rem", fontSize: "1.05rem", fontWeight: 700 }}>
          Two-Factor Authentication (2FA)
        </h3>
        <p style={{ margin: 0, fontSize: "0.875rem", color: "var(--muted)", lineHeight: 1.55 }}>
          Protect your account with an additional verification code generated by the SmartParking security system.
          Each time you sign in, you will be asked to enter a time-based code alongside your password.
        </p>
      </div>

      {!setup && (
        <div
          style={{
            display: "flex",
            alignItems: "center",
            gap: "1rem",
            padding: "0.875rem 1rem",
            borderRadius: "var(--radius)",
            border: "1px solid var(--border)",
            background: "var(--bg)",
          }}
        >
          <div
            style={{
              width: 40,
              height: 40,
              borderRadius: "50%",
              background: "var(--primary-subtle, #3b82f615)",
              color: "var(--primary)",
              display: "flex",
              alignItems: "center",
              justifyContent: "center",
              flexShrink: 0,
              fontSize: "1.25rem",
            }}
          >
            🔐
          </div>
          <div style={{ flex: 1 }}>
            <p style={{ margin: 0, fontWeight: 600, fontSize: "0.9rem" }}>
              SmartParking Security Code
            </p>
            <p style={{ margin: "0.125rem 0 0", fontSize: "0.8rem", color: "var(--muted)" }}>
              Uses a time-based code (TOTP) issued by the SmartParking system
            </p>
          </div>
          <button
            className="btn-outline"
            disabled={busy}
            onClick={() => void start()}
            style={{ flexShrink: 0 }}
          >
            {busy ? "Loading…" : "Set up 2FA"}
          </button>
        </div>
      )}

      {setup && (
        <form
          onSubmit={enable}
          style={{ display: "flex", flexDirection: "column", gap: "1rem" }}
        >
          <div
            style={{
              padding: "0.75rem 1rem",
              borderRadius: "var(--radius)",
              background: "#22c55e10",
              border: "1px solid #22c55e30",
              fontSize: "0.85rem",
              color: "#16a34a",
              lineHeight: 1.5,
            }}
          >
            <strong>Your security key has been generated.</strong> Copy the key
            below and save it in a secure location. It will be used to generate
            your sign-in verification codes.
          </div>

          <div>
            <p
              style={{
                margin: "0 0 0.375rem",
                fontSize: "0.85rem",
                fontWeight: 600,
              }}
            >
              Security Key
            </p>
            <div
              style={{
                fontFamily: "monospace",
                fontSize: "1rem",
                letterSpacing: "0.1em",
                padding: "0.625rem 0.875rem",
                borderRadius: "var(--radius)",
                background: "var(--bg)",
                border: "1px solid var(--border)",
                color: "var(--fg)",
                wordBreak: "break-all",
                userSelect: "all",
              }}
            >
              {setup.secret}
            </div>
            <p
              style={{
                margin: "0.375rem 0 0",
                fontSize: "0.775rem",
                color: "var(--muted)",
              }}
            >
              Keep this key private. Do not share it with anyone.
            </p>
          </div>

          <div>
            <label className="label" style={{ fontSize: "0.875rem" }}>
              Verification Code
              <input
                className="input"
                placeholder="Enter the 6-digit code to confirm setup"
                required
                pattern="[0-9]{6}"
                maxLength={6}
                inputMode="numeric"
                autoComplete="one-time-code"
                value={code}
                onChange={(e) => setCode(e.target.value)}
              />
            </label>
            <p
              style={{
                margin: "0.25rem 0 0",
                fontSize: "0.775rem",
                color: "var(--muted)",
              }}
            >
              Enter the 6-digit code generated for your account to confirm and
              activate 2FA.
            </p>
          </div>

          <div style={{ display: "flex", gap: "0.625rem", justifyContent: "flex-end" }}>
            <button
              type="button"
              className="btn-outline"
              disabled={busy}
              onClick={() => { setSetup(null); setCode(""); setMessage(""); }}
            >
              Cancel
            </button>
            <button className="btn-primary" disabled={busy}>
              {busy ? "Enabling…" : "Enable 2FA"}
            </button>
          </div>
        </form>
      )}

      {message && (
        <p
          role="status"
          style={{
            margin: 0,
            fontSize: "0.85rem",
            padding: "0.625rem 0.875rem",
            borderRadius: "var(--radius)",
            background: message.toLowerCase().includes("fail") || message.toLowerCase().includes("error")
              ? "#ef444415"
              : "#22c55e10",
            border: `1px solid ${message.toLowerCase().includes("fail") || message.toLowerCase().includes("error") ? "#ef444430" : "#22c55e30"}`,
            color: message.toLowerCase().includes("fail") || message.toLowerCase().includes("error")
              ? "#dc2626"
              : "#16a34a",
          }}
        >
          {message}
        </p>
      )}
    </section>
  )
}